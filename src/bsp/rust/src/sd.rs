// Host stand-ins for the bindgen `crate::sys` types used below (`block_device.h`
// / `types.h`). This is UNRELATED to `deluge_bsp::sd` now being dual-target —
// `mod sys` is generated by *this crate's* build.rs from the C++ app's headers,
// and build.rs skips bindgen entirely on host (no C++ app is linked there; see
// its top-of-file comment), so `crate::sys` simply doesn't exist to import on
// host, independent of what deluge-sdk exposes. Mirror the C types' shapes
// directly here instead (same convention as scheduler.rs's `RunCondition`):
// `DelugeStatus` is `i8` (its values run -13..=0, forcing a signed type; the
// header pins its underlying type explicitly — `enum DelugeStatus : int8_t`),
// `DelugeCardEvent` is `u8` (0..=2, pinned explicitly as `enum DelugeCardEvent
// : uint8_t`). Values match include/libdeluge/{types,block_device}.h exactly, so
// `deluge_block_poll_card_event` reports the same event vocabulary on both
// targets — though not by the same means: the device reads the SDHI's card-detect
// edge latches, while host has no card to remove and so has no edge to detect.
#[cfg(not(target_os = "none"))]
type DelugeStatus = i8;
#[cfg(not(target_os = "none"))]
const DELUGE_OK: DelugeStatus = 0;
#[cfg(not(target_os = "none"))]
const DELUGE_ERR_IO: DelugeStatus = -5;
#[cfg(not(target_os = "none"))]
const DELUGE_ERR_NODEV: DelugeStatus = -6;
#[cfg(not(target_os = "none"))]
const DELUGE_ERR_WRITE_PROTECTED: DelugeStatus = -12;

#[cfg(not(target_os = "none"))]
type DelugeCardEvent = u8;
#[cfg(not(target_os = "none"))]
const CARD_NONE: DelugeCardEvent = 0;
#[cfg(not(target_os = "none"))]
const CARD_INSERTED: DelugeCardEvent = 1;
#[cfg(not(target_os = "none"))]
const CARD_EJECTED: DelugeCardEvent = 2;

// FatFs diskio status/result codes (ChaN's FatFs `diskio.h` convention; no longer
// vendored in this tree, but these numeric values are the de-facto standard).
// Only the codes these shims actually return are declared — `RES_ERROR` (1) and
// `RES_WRPRT` (2) were carried over with the set and never used, and with C-FatFS deleted
// nothing is going to start using them, so they are gone rather than `#[allow]`ed.
const STA_NOINIT: u8 = 0x01;
const STA_NODISK: u8 = 0x02;
const STA_PROTECT: u8 = 0x04;
const RES_OK: i32 = 0;
const RES_NOTRDY: i32 = 3;
const RES_PARERR: i32 = 4;
const CTRL_SYNC: u8 = 0;
const GET_SECTOR_COUNT: u8 = 1;
const GET_SECTOR_SIZE: u8 = 2;
const GET_BLOCK_SIZE: u8 = 3;
const SECTOR_SIZE: usize = 512;

/// Set once `disk_initialize` has driven `sd::init()` at least once. Until then,
/// the controller has never muxed `SD_CD` (P7_0 → SDHI fn 3) or started `SD_CLK`,
/// so `sd::is_inserted()` reads a meaningless card-detect line. We must NOT report
/// `STA_NODISK` from that pre-init read: FatFS skips `disk_initialize` whenever the
/// disk looks absent, and `disk_initialize` is the only path that brings the detect
/// circuit to life — detection would be gated on init, and init on detection
/// (deadlock). Report "not initialized, presence unknown" instead so FatFS attempts
/// the init that makes card-detect valid. Device-only: `deluge_bsp::sd`'s host
/// stand-in has no controller bring-up step.
#[cfg(target_os = "none")]
static CONTROLLER_UP: AtomicBool = AtomicBool::new(false);

/// Bring the SD controller up from an async (Embassy task) context, once at boot.
///
/// `sd::init()` sequences card power-up with `embassy_time::Timer` delays. This BSP
/// uses the *integrated* (intrusive) timer queue, so a `Timer` only resolves when
/// polled by a real Embassy task — `embassy_futures::block_on`'s synthetic waker
/// makes `Timer` panic (`from_embassy_waker`). The sync FatFS `disk_initialize`
/// path can therefore never run `init()`. Instead we init here, from `app_task`,
/// before `deluge_app_init` drives the first C++ storage access: afterwards the card
/// reports ready, FatFS skips `disk_initialize`, and reads/writes stay on `block_on`
/// (pure SDHI/DMA-IRQ futures — no timers). Re-runnable for card-swap from async.
/// Device-only: `app_task` (this fn's sole caller) is itself device-only.
#[cfg(target_os = "none")]
pub async fn boot_init() {
    let r = sd::init().await;
    // The pin mux + SDHI bring-up has run, so card-detect is meaningful now.
    CONTROLLER_UP.store(true, Ordering::Release);
    log::info!(
        "sd: boot_init — init={:?} inserted={} wp={}",
        r.is_ok(),
        sd::is_inserted(),
        sd::is_write_protected(),
    );
}

/// Requests to (re-)identify the card, raised by [`deluge_block_poll_card_event`]
/// on an insertion edge and served by [`card_service`].
///
/// A `Signal` rather than a counter: what the service task needs to know is only
/// "a card that has not been identified is present", so coalescing several
/// insertion edges into one init is correct, not lossy.
#[cfg(target_os = "none")]
static CARD_INIT_REQ: embassy_sync::signal::Signal<CriticalSectionRawMutex, ()> =
    embassy_sync::signal::Signal::new();

/// Re-identifies the card after a swap, on a real Embassy task.
///
/// This exists because the work cannot be done anywhere else. `sd::init()` paces
/// the SD power-up sequence with `embassy_time::Timer`s, and this BSP uses the
/// *integrated* (intrusive) timer queue, where a `Timer` only resolves for a
/// genuine Embassy task waker — under `embassy_futures::block_on` it panics instead. So the card re-init cannot happen
/// inside the C-ABI storage entry points, which block on their transfers where a `Timer` is unavailable. The same
/// constraint is why `boot_init` runs from `app_task` rather than from the sync `disk_initialize` path.
///
/// Nothing waits on this task. It publishes its result through the card's own
/// ready state: `sd::init()` sets `CARD_READY`, so `deluge_block_ready()` —
/// hence the app's `StorageManager::checkSDPresent()` — flips to true when the
/// card is usable. The app's re-insert path (`AudioFileManager::reinitEjectedCard`,
/// called a couple of times a second from `slowRoutine`) already re-checks that
/// on every tick and re-mounts once it passes, so the handoff needs no
/// rendezvous: an attempt landing mid-init simply finds the card
/// not ready yet and retries on the next tick.
///
/// Holds [`SD_BUS`] across the init so the identification sequence cannot
/// interleave with a filesystem transfer or a streaming read on the one SDHI
/// controller. Storage-tier transfers wait it out and then run on the new card.
/// Interaction-tier transfers are refused while the card is not ready
/// (`acquire_bus`): they would otherwise spin on this lock on the very executor
/// this task needs to finish, and never return.
#[cfg(target_os = "none")]
#[embassy_executor::task]
pub async fn card_service() {
    loop {
        CARD_INIT_REQ.wait().await;
        let _guard = SD_BUS.lock().await;
        // Re-check presence under the lock: the card may have been pulled again
        // between the edge and here, in which case there is nothing to identify
        // and the next insertion edge will raise a fresh request.
        if !sd::is_inserted() {
            log::info!("sd: card gone again before re-init; waiting for the next insertion");
            continue;
        }
        match sd::init().await {
            Ok(()) => log::info!("sd: card re-identified after swap"),
            // Not fatal, and not retried here: an unreadable or half-seated card
            // leaves the app in its "ejected" state, still polling, and any later
            // reseat raises another insertion edge.
            Err(e) => log::warn!("sd: re-init after swap failed: {:?}", e),
        }
    }
}

/// `host_app` sibling of the device [`boot_init`] above: called from the host
/// `app_task` (`main.rs`) before `deluge_app_init`, purely to mirror the device
/// boot sequencing exactly. Not strictly required on host — unlike the device
/// (whose integrated timer queue makes `sd::init()`'s `Timer` delays unusable
/// under `disk_initialize`'s synchronous `block_on`, see the host
/// `disk_initialize` doc comment below), `deluge_bsp::sd`'s host `init()` never
/// suspends, so `disk_initialize` already drives it lazily via `block_on` on
/// first FatFS access with no separate async bring-up step needed. Calling it
/// here too is harmless (idempotent) and keeps the host and device `app_task`
/// bodies textually identical.
#[cfg(all(not(target_os = "none"), feature = "host_app"))]
pub async fn boot_init() {
    let r = sd::init().await;
    log::info!(
        "sd: boot_init (host) — init={:?} inserted={} wp={}",
        r.is_ok(),
        sd::is_inserted(),
        sd::is_write_protected(),
    );
}

/// Take [`SD_BUS`] for one transfer.
///
/// An INTERACTION-tier caller fails fast with `NotInitialized` while the card is not ready. That caller is a
/// synchronous spin on the thread executor, and `card_service` holds the bus across the whole of a card's
/// identification on that same executor: waiting would spin forever, with the only executor that could finish
/// the identification occupied by the spin. Readiness is re-checked on every poll, and every identification
/// follows an `invalidate()`, so a caller that arrives during one is refused at once.
///
/// Every other tier waits as it always has. A storage-tier read runs on its own executor, lets the
/// identification finish, and then succeeds on the re-identified card; failing it instead would push a
/// re-inserted card's samples down the error path.
async fn acquire_bus()
-> Result<embassy_sync::mutex::MutexGuard<'static, CriticalSectionRawMutex, ()>, sd::SdError> {
    let mut lock = core::pin::pin!(SD_BUS.lock());
    core::future::poll_fn(move |cx| {
        if crate::tier::current() == crate::tier::Tier::Interaction && !sd::is_ready() {
            return core::task::Poll::Ready(Err(sd::SdError::NotInitialized));
        }
        core::future::Future::poll(lock.as_mut(), cx).map(Ok)
    })
    .await
}

/// Thin async wrapper around `deluge_bsp::sd::read_sectors` for the streaming
/// fill task (`streaming_loader.rs`). Same dual-target shape as the rest of this
/// file — no `#[cfg]` needed at the call site. Serializes on [`SD_BUS`] against
/// the FatFS transfers (`deluge_block_read`/`deluge_block_write` below, which
/// route through this same function), so the two never drive the single SDHI
/// controller concurrently.
///
/// In `sim_latency` host builds this dispatches to
/// [`sim_latency::modeled_read`] instead of the raw (instant)
/// `sd::read_sectors`, so the streaming task's reads pend on the same modeled
/// SD latency the `deluge_block_read` (`sim_latency` variant, below)
/// already uses — otherwise Lens-1's fill-margin measurement would be
/// meaningless (task reads completing instantly instead of at the modeled SD
/// throughput). `modeled_read` does NOT itself touch [`SD_BUS`] (it only
/// awaits [`sim_latency::delay`] then calls the raw `sd::read_sectors`), so
/// this stays a single `SD_BUS` acquisition — no nested/double lock. This is
/// also a distinct code path from the `sim_latency` `deluge_block_read`
/// below, which has its own bespoke inline lock+`modeled_read` call and does
/// NOT route through this function — so no double-modeling either.
pub async fn locked_read_sectors(lba: u32, count: u32, buf: &mut [u8]) -> Result<(), sd::SdError> {
    let _guard = acquire_bus().await?;
    // The common chokepoint for block reads regardless of
    // backend — both the delegating plain-host `deluge_block_read` (below)
    // and efatfs's `HostSdBlockDevice::read` (efatfs_host_shim.rs) route
    // through here, so counting once at this call site covers both without
    // double-counting (the `sim_latency` `deluge_block_read` variant does
    // its own bespoke transfer and is instrumented separately — see its doc
    // comment). Host-only, matching `stats`'s own `#[cfg]`.
    #[cfg(not(target_os = "none"))]
    stats::note_read();
    #[cfg(all(not(target_os = "none"), feature = "sim_latency"))]
    {
        // Model EVERY transfer. This used to have an escape hatch
        // (`sim_latency::off_fiber_instant`) that skipped modeling and took the real
        // synchronous read, because a caller off the (since retired) worker fiber arrived through a NON-yielding
        // `embassy_futures::block_on` — and awaiting `modeled_read`'s `Timer` under a hookless
        // spin livelocks, since nothing can poll `sim_latency::pump` while the spin never
        // returns. That was confirmed empirically at the time (100% CPU, virtual clock frozen).
        //
        // The escape hatch is gone because its premise is: storage now spins through
        // `crate::sim_block::block_on`, whose progress hook pumps the executor hosting `pump`
        // and advances the virtual clock on every `Pending`. So the `Timer` the hatch existed to
        // avoid is exactly what the hook completes. Consequence, and the point of removing it:
        // task-context reads get modeled latency for the first time, so Lens 1 sees them.
        sim_latency::modeled_read(lba, count, buf).await
    }
    #[cfg(not(all(not(target_os = "none"), feature = "sim_latency")))]
    {
        sd::read_sectors(lba, count, buf).await
    }
}

/// Write sibling of [`locked_read_sectors`] — same [`SD_BUS`] serialization,
/// same `sim_latency`-dispatch shape (routes to [`sim_latency::modeled_write`]),
/// same write instrumentation (see the read sibling's doc comment).
pub async fn locked_write_sectors(lba: u32, count: u32, buf: &[u8]) -> Result<(), sd::SdError> {
    let _guard = acquire_bus().await?;
    #[cfg(not(target_os = "none"))]
    stats::note_write();
    #[cfg(all(not(target_os = "none"), feature = "sim_latency"))]
    {
        sim_latency::modeled_write(lba, count, buf).await
    }
    #[cfg(not(all(not(target_os = "none"), feature = "sim_latency")))]
    {
        sd::write_sectors(lba, count, buf).await
    }
}

/// FatFS DSTATUS bits for the current card state. Device-only (see [`sd`]).
#[cfg(target_os = "none")]
fn status_bits() -> u8 {
    // DIAG (SD bring-up): log the raw card-detect/ready state the first few times
    // status is queried, so "No SD card present" can be traced to is_inserted()
    // vs. is_ready() vs. init failure.
    {
        static DIAG_LEFT: AtomicBool = AtomicBool::new(true);
        if DIAG_LEFT.swap(false, Ordering::Relaxed) {
            log::info!(
                "DIAG sd: status_bits — inserted={} ready={} wp={}",
                sd::is_inserted(),
                sd::is_ready(),
                sd::is_write_protected(),
            );
        }
    }
    if !sd::is_ready() {
        // Only trust the card-detect read once the controller has been brought up.
        let absent = CONTROLLER_UP.load(Ordering::Acquire) && !sd::is_inserted();
        return STA_NOINIT | if absent { STA_NODISK } else { 0 };
    }
    if sd::is_write_protected() {
        STA_PROTECT
    } else {
        0
    }
}

#[cfg(target_os = "none")]
#[unsafe(no_mangle)]
pub extern "C" fn disk_initialize(pdrv: u8) -> u8 {
    if pdrv != 0 {
        return STA_NOINIT;
    }
    // sd::init() can't run here: its embassy-time Timers panic under `block_on`
    // (integrated timer queue — see `boot_init`). It runs eagerly from `app_task`
    // (boot_init) after the PIC baud handshake (pic::wait_ready) and before
    // deluge_app_init — waiting for the PIC first avoids the handshake race that
    // corrupted the pads. So the card is ready by the time the app first calls this;
    // if somehow not, just report status (never block_on(init) here).
    if !sd::is_ready() {
        log::warn!("sd: disk_initialize before async init done");
    }
    status_bits()
}

#[cfg(target_os = "none")]
#[unsafe(no_mangle)]
pub extern "C" fn disk_status(pdrv: u8) -> u8 {
    if pdrv != 0 {
        return STA_NOINIT;
    }
    status_bits()
}

/// Host: no controller bring-up or card-detect exists — `deluge_bsp::sd`'s
/// file-backed disk image is ready as soon as it can be opened/sized.
/// `sd::init()` never suspends on host (there's no hardware to await), so
/// unlike the device path (see [`boot_init`]) it's safe to drive to completion
/// with `block_on` right here rather than needing a separate async bring-up
/// step. Both FatFS DSTATUS entry points then just report "ready" for unit 0.
#[cfg(not(target_os = "none"))]
#[unsafe(no_mangle)]
pub extern "C" fn disk_initialize(pdrv: u8) -> u8 {
    if pdrv != 0 {
        return STA_NOINIT;
    }
    let _ = block_on(sd::init());
    0
}

#[cfg(not(target_os = "none"))]
#[unsafe(no_mangle)]
pub extern "C" fn disk_status(pdrv: u8) -> u8 {
    if pdrv != 0 {
        return STA_NOINIT;
    }
    0
}

/// block_device.h — true if the card is present and initialised. A safe
/// superset of the app's old `!(disk_status(unit) & STA_NODISK)` card-detect
/// check: this also folds in `STA_NOINIT`, which is fine because the app's
/// `initSD` immediately requires full readiness for the mount that follows
/// anyway (see `storage_manager.cpp`'s `initSD`/`checkSDInitialized`).
#[cfg(target_os = "none")]
#[unsafe(no_mangle)]
pub extern "C" fn deluge_block_ready(unit: u8) -> bool {
    if unit != 0 {
        return false;
    }
    status_bits() & (STA_NOINIT | STA_NODISK) == 0
}

/// Host: mirrors `disk_status` above — the file-backed disk image is always
/// ready once openable, no controller bring-up or card-detect to model.
#[cfg(not(target_os = "none"))]
#[unsafe(no_mangle)]
pub extern "C" fn deluge_block_ready(unit: u8) -> bool {
    unit == 0
}

#[unsafe(no_mangle)]
pub extern "C" fn disk_ioctl(pdrv: u8, cmd: u8, buff: *mut core::ffi::c_void) -> i32 {
    if pdrv != 0 {
        return RES_NOTRDY;
    }
    match cmd {
        // Writes complete synchronously (block_on / a direct host file write), so
        // nothing is ever pending.
        CTRL_SYNC => RES_OK,
        GET_SECTOR_COUNT => {
            if buff.is_null() {
                return RES_PARERR;
            }
            // No `#[cfg]` needed here: `sd::total_sectors()` resolves to the
            // device SDHI driver or the host file-backed image internally.
            let sectors = sd::total_sectors();
            unsafe { *(buff as *mut u32) = sectors };
            RES_OK
        }
        GET_SECTOR_SIZE => {
            if buff.is_null() {
                return RES_PARERR;
            }
            unsafe { *(buff as *mut u16) = SECTOR_SIZE as u16 };
            RES_OK
        }
        GET_BLOCK_SIZE => {
            if buff.is_null() {
                return RES_PARERR;
            }
            unsafe { *(buff as *mut u32) = 1 };
            RES_OK
        }
        _ => RES_PARERR,
    }
}

// FatFS is not re-entrant. The app's SD-reentrancy guard is
// `deluge_storage_fs_busy()`, which this BSP backs with the efatfs FS-mutex
// state (see `efatfs_fs.rs`), so it now genuinely reflects whether a FatFS
// transfer is in flight rather than being a dead always-0 flag. But that
// guard only lets callers *detect* an in-flight transfer and back off — it
// does nothing to prevent two tasks from entering FatFS concurrently in the
// first place. Yielding mid-transfer unconditionally would still let other
// tasks re-enter FatFS concurrently and corrupt it (manifests as "NO MORE
// PRESETS FOUND" on track create, and would also break song/sample loads).
// These transfer sites therefore park via `block_on`: nothing else enters FatFS while one runs. (A retired storage
// worker fiber once yielded mid-transfer here, safe only because every FatFS call came from that one fiber.)
#[cfg(target_os = "none")]
#[unsafe(no_mangle)]
pub extern "C" fn deluge_block_read(
    unit: u8,
    dst: *mut u8,
    sector: u32,
    count: u32,
) -> DelugeStatus {
    crate::tier_meter::note(crate::tier_meter::Entry::BlockRead);
    if unit != 0 || !sd::is_ready() {
        return DELUGE_ERR_NODEV;
    }
    let len = count as usize * SECTOR_SIZE;
    // SAFETY: caller guarantees `dst` holds `count` sectors.
    let out = unsafe { core::slice::from_raw_parts_mut(dst, len) };
    let fut = locked_read_sectors(sector, count, out);
    match block_on(fut) {
        Ok(()) => DELUGE_OK,
        Err(_) => DELUGE_ERR_IO,
    }
}

#[cfg(target_os = "none")]
#[unsafe(no_mangle)]
pub extern "C" fn deluge_block_write(
    unit: u8,
    src: *const u8,
    sector: u32,
    count: u32,
) -> DelugeStatus {
    crate::tier_meter::note(crate::tier_meter::Entry::BlockWrite);
    if unit != 0 || !sd::is_ready() {
        return DELUGE_ERR_NODEV;
    }
    if sd::is_write_protected() {
        return DELUGE_ERR_WRITE_PROTECTED;
    }
    let len = count as usize * SECTOR_SIZE;
    // SAFETY: caller guarantees `src` holds `count` sectors.
    let data = unsafe { core::slice::from_raw_parts(src, len) };
    let fut = locked_write_sectors(sector, count, data);
    match block_on(fut) {
        Ok(()) => DELUGE_OK,
        Err(e) => {
            log::warn!("deluge_block_write err {e:?} (sector={sector} count={count})");
            DELUGE_ERR_IO
        }
    }
}

/// Host-only instrumentation (streaming-underrun harness): counts every SD block read and write. `scenario.rs` reports
/// them as `cluster_reads`/`recorder_writes`, and `lens1_vt_sim` as `card_reads`/`card_writes`. Compiled for every host
/// build (not gated on `host_app`/`sim_latency`); the counters sit idle unless something reads them.
///
/// These once counted only the transfers made on the storage worker fiber, which was every transfer until storage
/// became callable from any context. The fiber is retired, and they count everything.
///
/// The `note_read`/`note_write` call sites live at [`locked_read_sectors`]/
/// [`locked_write_sectors`] — the chokepoint both the plain-host `deluge_block_*`
/// wrappers (which delegate to them) AND efatfs's `HostSdBlockDevice` (which
/// calls them directly, bypassing the C-ABI `deluge_block_*` entry points
/// entirely) pass through — plus the `sim_latency` `deluge_block_*` variants,
/// which do their own bespoke transfer and are instrumented at their own call
/// site instead (they never reach `locked_*_sectors`). Each transfer is counted
/// at exactly one of those two kinds of site, never both.
#[cfg(not(target_os = "none"))]
pub(crate) mod stats {
    use core::sync::atomic::{AtomicU64, Ordering};

    static READS: AtomicU64 = AtomicU64::new(0);
    static WRITES: AtomicU64 = AtomicU64::new(0);

    pub(crate) fn note_read() {
        READS.fetch_add(1, Ordering::Relaxed);
    }

    pub(crate) fn note_write() {
        WRITES.fetch_add(1, Ordering::Relaxed);
    }

    /// Total SD block reads, any backend (the plain/`sim_latency` `deluge_block_read`, or efatfs's
    /// `HostSdBlockDevice::read` via `locked_read_sectors`).
    pub fn reads() -> u64 {
        READS.load(Ordering::Relaxed)
    }

    /// Total SD block writes, any backend (the plain/`sim_latency` `deluge_block_write`, or efatfs's
    /// `HostSdBlockDevice::write` via `locked_write_sectors`).
    pub fn writes() -> u64 {
        WRITES.load(Ordering::Relaxed)
    }
}

/// Host: read `count` sectors via `deluge_bsp::sd::read_sectors` — the SAME
/// call the device path (above) makes, now backed by `deluge_bsp::sd`'s
/// file-backed disk image instead of a local shim. No card-detect concept on
/// host — `DELUGE_ERR_NODEV` is only for a non-zero unit. Deliberately does
/// NOT gate on `sd::is_ready()` (unlike the device path): the host image is
/// usable as soon as `deluge_bsp::sd` lazily opens/sizes its backing file on
/// first access, with no async bring-up step required first, and the host
/// harness's round-trip check (see `main.rs`) exercises this ABI directly
/// without calling `disk_initialize`/`sd::init()` beforehand.
///
/// `sim_latency`-off only: with that feature on, [`sim_latency`]'s sibling
/// below (same signature) takes over — see its doc comment.
#[cfg(all(not(target_os = "none"), not(feature = "sim_latency")))]
#[unsafe(no_mangle)]
pub extern "C" fn deluge_block_read(
    unit: u8,
    dst: *mut u8,
    sector: u32,
    count: u32,
) -> DelugeStatus {
    crate::tier_meter::note(crate::tier_meter::Entry::BlockRead);
    if unit != 0 {
        return DELUGE_ERR_NODEV;
    }
    // `locked_read_sectors` (below) does the counting — this
    // path delegates straight to it, so instrumenting here too would
    // double-count. See `locked_read_sectors`'s doc comment.
    let len = count as usize * SECTOR_SIZE;
    // SAFETY: caller guarantees `dst` holds `count` sectors.
    let out = unsafe { core::slice::from_raw_parts_mut(dst, len) };
    match block_on(locked_read_sectors(sector, count, out)) {
        Ok(()) => DELUGE_OK,
        Err(e) => {
            log::warn!("deluge_block_read(host) err {e:?} (sector={sector} count={count})");
            DELUGE_ERR_IO
        }
    }
}

/// Host: write `count` sectors via `deluge_bsp::sd::write_sectors` (see
/// [`deluge_block_read`] above for why there's no `is_ready()` gate here).
/// `sd::is_write_protected()` is still checked — it always reads `false` on
/// host (a plain file has no write-protect concept), so this is a no-op today,
/// but it keeps the call site identical to the device path.
///
/// `sim_latency`-off only: with that feature on, [`sim_latency`]'s sibling
/// below (same signature) takes over — see its doc comment.
#[cfg(all(not(target_os = "none"), not(feature = "sim_latency")))]
#[unsafe(no_mangle)]
pub extern "C" fn deluge_block_write(
    unit: u8,
    src: *const u8,
    sector: u32,
    count: u32,
) -> DelugeStatus {
    crate::tier_meter::note(crate::tier_meter::Entry::BlockWrite);
    if unit != 0 {
        return DELUGE_ERR_NODEV;
    }
    if sd::is_write_protected() {
        return DELUGE_ERR_WRITE_PROTECTED;
    }
    // `locked_write_sectors` (below) does the counting — this
    // path delegates straight to it, so instrumenting here too would
    // double-count. See `locked_read_sectors`'s doc comment.
    let len = count as usize * SECTOR_SIZE;
    // SAFETY: caller guarantees `src` holds `count` sectors.
    let data = unsafe { core::slice::from_raw_parts(src, len) };
    match block_on(locked_write_sectors(sector, count, data)) {
        Ok(()) => DELUGE_OK,
        Err(e) => {
            log::warn!("deluge_block_write(host) err {e:?} (sector={sector} count={count})");
            DELUGE_ERR_IO
        }
    }
}

/// Host, `sim_latency` feature: same file-backed data path as the plain host
/// `deluge_block_read` above, but the transfer future is wrapped by
/// [`sim_latency::modeled_read`], which pends on a MODELED per-transfer
/// latency ([`sim_latency::latency_for`]) before completing with the real
/// file-image data, driven through `sim_block::block_on`, whose progress hook
/// pumps the executor hosting [`sim_latency::pump`] and advances the virtual
/// clock, so the modeled delay elapses and a harness can measure the
/// fill-vs-drain race — see `sim_latency`'s module doc.
///
/// Mutually exclusive with the plain host `deluge_block_read` above (disjoint
/// `#[cfg]`s): with `sim_latency` off, this function does not exist and the
/// plain sibling compiles unchanged, so normal host/device/golden builds are
/// byte-identical to before this feature existed.
#[cfg(all(not(target_os = "none"), feature = "sim_latency"))]
#[unsafe(no_mangle)]
pub extern "C" fn deluge_block_read(
    unit: u8,
    dst: *mut u8,
    sector: u32,
    count: u32,
) -> DelugeStatus {
    crate::tier_meter::note(crate::tier_meter::Entry::BlockRead);
    if unit != 0 {
        return DELUGE_ERR_NODEV;
    }
    stats::note_read();
    let len = count as usize * SECTOR_SIZE;
    // SAFETY: caller guarantees `dst` holds `count` sectors.
    let out = unsafe { core::slice::from_raw_parts_mut(dst, len) };
    // SD_BUS is locked inside each transfer future (not via `locked_read_sectors`
    // — this path calls `sim_latency::modeled_read`, not `sd::read_sectors`, so it
    // can't reuse that helper). Locked once per branch, at the same single level
    // as every other entry point — never nested.
    let result = crate::sim_block::block_on(async {
        let _guard = SD_BUS.lock().await;
        sim_latency::modeled_read(sector, count, out).await
    });
    match result {
        Ok(()) => DELUGE_OK,
        Err(e) => {
            log::warn!(
                "deluge_block_read(host, sim_latency) err {e:?} (sector={sector} count={count})"
            );
            DELUGE_ERR_IO
        }
    }
}

/// Host, `sim_latency` feature: write sibling of [`deluge_block_read`]
/// (above) — see its doc comment for the full rationale.
#[cfg(all(not(target_os = "none"), feature = "sim_latency"))]
#[unsafe(no_mangle)]
pub extern "C" fn deluge_block_write(
    unit: u8,
    src: *const u8,
    sector: u32,
    count: u32,
) -> DelugeStatus {
    crate::tier_meter::note(crate::tier_meter::Entry::BlockWrite);
    if unit != 0 {
        return DELUGE_ERR_NODEV;
    }
    if sd::is_write_protected() {
        return DELUGE_ERR_WRITE_PROTECTED;
    }
    stats::note_write();
    let len = count as usize * SECTOR_SIZE;
    // SAFETY: caller guarantees `src` holds `count` sectors.
    let data = unsafe { core::slice::from_raw_parts(src, len) };
    // See the read sibling's identical comment above: SD_BUS locked inline per
    // branch (this path calls `sim_latency::modeled_write`, not
    // `sd::write_sectors`, so it can't reuse `locked_write_sectors`).
    let result = crate::sim_block::block_on(async {
        let _guard = SD_BUS.lock().await;
        sim_latency::modeled_write(sector, count, data).await
    });
    match result {
        Ok(()) => DELUGE_OK,
        Err(e) => {
            log::warn!(
                "deluge_block_write(host, sim_latency) err {e:?} (sector={sector} count={count})"
            );
            DELUGE_ERR_IO
        }
    }
}

/// Sim-only (harness) modeled-latency substrate for host SD transfers. Gated
/// entirely behind the `sim_latency` cargo feature (OFF by default — see
/// `Cargo.toml`'s doc comment), so a normal host/device/golden build never
/// compiles any of this in.
///
/// ## Why the modeled delay can't just be `Timer::after(...).await`ed inline
///
/// The obvious shape — have `deluge_block_read`'s future do
/// `Timer::after(latency_for(bytes)).await` directly, then call
/// `sd::read_sectors` — does NOT work when that future is driven by a
/// `block_on`: it polls the future with a synthetic `Waker` that is not a
/// genuine embassy-executor TASK waker,
/// and `embassy-time`'s integrated timer queue (this workspace pins the
/// `timer-item-size-*`/integrated variant — see `Cargo.toml`'s patch section)
/// panics on exactly that (`TimerQueueItem::from_embassy_waker`: "Panics if
/// called with a non-embassy waker"). This is the same constraint already
/// documented at this file's `boot_init` (`sd::init()`'s Timers can't run
/// under `block_on`).
///
/// So the actual `Timer::after` await happens in [`pump`], a genuine spawned
/// Embassy task (a real per-task waker — whichever executor/harness spawns
/// it, on the virtual `MockDriver` clock or the host `std` clock, per
/// `embassy-time`'s linked driver; this module never touches a clock
/// directly). [`delay`] hands `pump` a duration over a `Signal` and awaits
/// completion via a plain [`embassy_sync::waitqueue::AtomicWaker`] — safe to
/// poll from ANY waker, including `block_on`'s synthetic one.
///
/// Every modeled transfer runs holding [`SD_BUS`], so at most one is ever in
/// flight — a single request/completion slot suffices; no per-transfer task
/// spawning or queueing is needed.
#[cfg(all(not(target_os = "none"), feature = "sim_latency"))]
pub mod sim_latency {
    use core::future::Future;
    use core::pin::Pin;
    use core::sync::atomic::{AtomicBool, AtomicU32, Ordering};
    use core::task::{Context, Poll};

    use deluge_bsp::sd;
    use embassy_sync::blocking_mutex::raw::CriticalSectionRawMutex;
    use embassy_sync::signal::Signal;
    use embassy_sync::waitqueue::AtomicWaker;
    use embassy_time::{Duration, Timer};

    use super::SECTOR_SIZE;

    /// Modeled throughput, bytes/sec — the `bytes / throughput` term of the
    /// latency model. Overridable at runtime (a plain `Relaxed` static, not a
    /// `const`) so a harness sweep can vary it per run without a rebuild.
    /// Default: a plausible sustained SD sequential-transfer rate.
    static THROUGHPUT_BYTES_PER_SEC: AtomicU32 = AtomicU32::new(20_000_000);
    /// Modeled fixed per-command overhead, microseconds — the command/
    /// response round-trip latency independent of transfer size. Overridable
    /// for the same reason as [`THROUGHPUT_BYTES_PER_SEC`].
    static COMMAND_OVERHEAD_US: AtomicU32 = AtomicU32::new(500);

    /// Override the modeled throughput (bytes/sec; clamped to at least 1 so
    /// [`latency_for`] never divides by zero).
    pub fn set_throughput_bytes_per_sec(bytes_per_sec: u32) {
        THROUGHPUT_BYTES_PER_SEC.store(bytes_per_sec.max(1), Ordering::Relaxed);
    }

    /// Override the modeled fixed command overhead (microseconds).
    pub fn set_command_overhead_us(us: u32) {
        COMMAND_OVERHEAD_US.store(us, Ordering::Relaxed);
    }

    /// Modeled latency for a `bytes`-byte transfer: fixed command overhead
    /// plus `bytes / throughput`. A simple throughput + fixed-overhead model
    /// (not a hardware-accurate SD timing simulation) — sufficient for a
    /// harness to observe a fill-vs-drain race, and cheap to reason about.
    pub fn latency_for(bytes: usize) -> Duration {
        let throughput_bps = THROUGHPUT_BYTES_PER_SEC.load(Ordering::Relaxed) as u64;
        let overhead_us = COMMAND_OVERHEAD_US.load(Ordering::Relaxed) as u64;
        let transfer_us = (bytes as u64 * 1_000_000) / throughput_bps;
        Duration::from_micros(overhead_us + transfer_us)
    }

    /// Single-flight request handoff to [`pump`]: the duration for the
    /// in-flight modeled transfer. A single slot suffices — see the module
    /// doc's serialization note.
    static REQUEST: Signal<CriticalSectionRawMutex, Duration> = Signal::new();
    /// Set by [`pump`] once its `Timer` for the current request has elapsed;
    /// cleared by [`DelayFuture`]'s poll on consumption.
    static DONE: AtomicBool = AtomicBool::new(false);
    /// Woken by [`pump`] on completion; registered by [`DelayFuture`]'s poll.
    /// A plain waitqueue primitive — safe to be woken from, or register a
    /// waker from, any thread/context, unlike `embassy-time`'s Timer (see the
    /// module doc).
    static WAKER: AtomicWaker = AtomicWaker::new();

    /// Background task: the ONLY place in this module that actually awaits
    /// `embassy_time::Timer` — see the module doc for why. Must be spawned
    /// once onto whichever Embassy executor the harness brings up before any `sim_latency`
    /// transfer is issued; loops forever, one modeled delay at a time.
    #[embassy_executor::task]
    pub async fn pump() {
        loop {
            let dur = REQUEST.wait().await;
            Timer::after(dur).await;
            DONE.store(true, Ordering::SeqCst);
            WAKER.wake();
        }
    }

    /// A completion future safe to poll from any `Waker` — including
    /// `block_on`'s synthetic one (see the module doc). Registers with [`WAKER`] before
    /// checking [`DONE`] (register-then-check ordering avoids a lost wake if
    /// [`pump`] completes between the check and the registration).
    struct DelayFuture;
    impl Future for DelayFuture {
        type Output = ();
        fn poll(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<()> {
            WAKER.register(cx.waker());
            if DONE.swap(false, Ordering::SeqCst) {
                Poll::Ready(())
            } else {
                Poll::Pending
            }
        }
    }

    /// Await the modeled latency for a `bytes`-byte transfer, driven by
    /// [`pump`].
    async fn delay(bytes: usize) {
        REQUEST.signal(latency_for(bytes));
        DelayFuture.await;
    }

    /// The modeled-latency wrapper future for a host read: pends on the
    /// modeled per-transfer delay, then performs the real (synchronous,
    /// file-backed) read. Only the timing is modeled; the data comes from
    /// the same `deluge_bsp::sd::read_sectors` the plain host path uses.
    pub async fn modeled_read(lba: u32, count: u32, buf: &mut [u8]) -> Result<(), sd::SdError> {
        delay(count as usize * SECTOR_SIZE).await;
        sd::read_sectors(lba, count, buf).await
    }

    /// Write sibling of [`modeled_read`].
    pub async fn modeled_write(lba: u32, count: u32, buf: &[u8]) -> Result<(), sd::SdError> {
        delay(count as usize * SECTOR_SIZE).await;
        sd::write_sectors(lba, count, buf).await
    }
}

