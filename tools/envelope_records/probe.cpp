// Drives main's envelope (modulation/envelope.cpp at e223d19d5, built by make_records.sh) through every stimulus of
// tests/unit/dsp/main_envelope_stimuli.h and prints tests/unit/dsp/main_envelope_records.h: each render's word and
// stage. A note-off follows main's Envelope::noteOff with Sound::envelopeHasSustainCurrently's rule per mode, and a
// retrigger follows main's Voice: the level before the note-on, the note-on, then resumeAttack.

#include "main_envelope_stimuli.h"
#include "modulation/envelope.h"

#include <cstdint>
#include <cstdio>
#include <new>
#include <vector>

namespace me = deluge::test::main_envelope;
using deluge::modulation::EnvelopeConfig;
using deluge::modulation::EnvelopeMode;

namespace {

struct Render {
	int32_t word;
	uint8_t stage;
};

std::vector<Render> run(const me::Stimulus& s) {
	alignas(Envelope) unsigned char storage[sizeof(Envelope)]{};
	auto* env = new (storage) Envelope(); // main's constructor sets nothing; the zeroed storage is its start
	EnvelopeConfig config;
	config.mode = static_cast<EnvelopeMode>(s.mode);
	config.setCurve(s.curve);
	std::vector<Render> out;
	const me::Params first = me::params_at(s, 0);
	env->noteOn(s.directly_to_decay, first.sustain, config.mode);
	for (uint32_t b = 0; b < s.blocks; ++b) {
		const me::Params p = me::params_at(s, b);
		if (b == s.note_off) {
			const bool has_sustain = s.mode == me::Mode::AHD                               ? false
			                         : (s.mode == me::Mode::AR || s.mode == me::Mode::MPE) ? true
			                                                                               : s.has_sustain;
			if (!has_sustain) {
				env->ignoredNoteOff = true;
			}
			else if (env->state < EnvelopeStage::RELEASE) {
				env->unconditionalRelease();
			}
		}
		if (b == s.fast_release) {
			env->unconditionalRelease(EnvelopeStage::FAST_RELEASE, SOFT_CULL_INCREMENT);
		}
		if (b == s.retrigger) {
			const float old = env->lastValue;
			env->noteOn(s.directly_to_decay, p.sustain, config.mode);
			env->resumeAttack(old, config);
		}
		const int32_t word = env->render(s.block, p.attack, p.decay, static_cast<uint32_t>(p.sustain), p.release,
		                                 config, me::follow_at(s, b));
		out.push_back({word, static_cast<uint8_t>(env->state)});
	}
	env->~Envelope();
	return out;
}

} // namespace

int main() {
	std::printf(
	    "// Generated by tools/envelope_records/make_records.sh from main's modulation/envelope.cpp at e223d19d5:\n"
	    "// each stimulus of main_envelope_stimuli.h, one render's centred word and stage per block. Do not edit.\n"
	    "\n#pragma once\n\n#include \"main_envelope_stimuli.h\"\n\n#include <array>\n#include <cstdint>\n\n"
	    "namespace deluge::test::main_envelope {\n\n"
	    "/// @brief One stimulus's renders.\nstruct Record {\n\tconst int32_t* words;\n\tconst uint8_t* stages;\n"
	    "\tuint32_t count;\n};\n\n");
	std::vector<size_t> counts;
	for (size_t i = 0; i < me::kStimuli.size(); ++i) {
		const std::vector<Render> r = run(me::kStimuli[i]);
		counts.push_back(r.size());
		std::printf("inline constexpr int32_t kWords%zu[] = {", i);
		for (const Render& x : r) {
			std::printf("%d,", x.word);
		}
		std::printf("};\ninline constexpr uint8_t kStages%zu[] = {", i);
		for (const Render& x : r) {
			std::printf("%u,", static_cast<unsigned>(x.stage));
		}
		std::printf("};\n");
	}
	std::printf("\n/// @brief Every stimulus's renders, in kStimuli's order.\n"
	            "inline constexpr std::array<Record, kCount> kRecords{{\n");
	for (size_t i = 0; i < counts.size(); ++i) {
		std::printf("    {kWords%zu, kStages%zu, %zu},\n", i, i, counts[i]);
	}
	std::printf("}};\n\n} // namespace deluge::test::main_envelope\n");
	return 0;
}
