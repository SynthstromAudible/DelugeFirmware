// The tables that name params, recorded cell by cell as runtime (kind, index) from next d70387530 before they named
// params by target: the oracle each target table is checked against through the bridge. A cell is the table's own
// position: grid cells x * 8 + y; knob cells mode * 2 + knob, and for the global effectable's
// (((mode * 2 + knob) * 3 + filter type) * 3 + mod FX param) * 2 + editing compressor. An empty cell is kind NONE,
